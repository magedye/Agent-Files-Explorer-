#!/usr/bin/env python3
"""Read-only AGHR Minimal distribution validator (Python 3.10+).

No project writes, tool execution, external access, or host qualification.
Hashes are integrity baselines, not authenticated signatures.
"""
from __future__ import annotations
import argparse
import hashlib
import json
import os
import re
from pathlib import Path, PurePosixPath
from typing import Any
from urllib.parse import unquote, urlsplit

VERSION = "1.1.0"
EXPECTED_RULE_IDS = {f"AGHR-{n:03}" for n in range(1, 48)}
PRESERVED_HASHES = {'CHARTER.md': 'a60d2251398e5cfdf498adb3751077d3f07fdcc36e38d367c64108c65dd37be6', 'LICENSE.md': '7f75e60dba65417b72dea6e6bcae745a80bff8fb2fe93ec1b74278763dc6b77e', 'registry/RULES.json': 'bc37e2eab25b2e7c8fa7e50a837f25ed7862694d9fa2637e3200659c2a887d62', 'sources/REGISTER.json': '6a5055130d2f46ba85a17ec6d13195da5b938f402f5bb9f77e1c9fbab65fc431', 'sources/REFERENCE_POLICY.md': 'a0175d57999ab9d9d34f5512566a64b3319d2b96eedb0cdf5855f3821790efe4', 'profiles/README.md': '35b08840db735a0db655c112840d9feed2b880e0009e50c8b8a4a3e6e8b0ea09', 'templates/OPERATING_CONTRACT.md': 'a3a9a3a34fd85816eff9ebfda164d3c4a8e1c28f225d5c268d12e07f054157e8'}
SOURCE_ARCHIVE_SHA256 = "ff6048d6c96fda6110b460ce93eb32a50e01830c58e921d921c950f2434dd206"
MAX_FILE_BYTES = 2_000_000
MAX_FILES = 500
QUALIFICATION = {
    "project_adoption": "NOT_PERFORMED",
    "host": "NOT_RUN",
    "model_behavior": "NOT_RUN",
    "independent_review": "NOT_PERFORMED",
    "production_activation": "NOT_PERFORMED",
}

class InvalidDistribution(ValueError):
    pass

def digest(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()

def _no_duplicate_keys(pairs: list[tuple[str, Any]]) -> dict[str, Any]:
    out: dict[str, Any] = {}
    for k, v in pairs:
        if k in out:
            raise InvalidDistribution(f"duplicate JSON key: {k}")
        out[k] = v
    return out

def load_json(data: bytes) -> Any:
    return json.loads(data.decode("utf-8"), object_pairs_hook=_no_duplicate_keys,
                      parse_constant=lambda x: (_ for _ in ()).throw(InvalidDistribution("non-finite JSON number")))

def safe_path(root: Path, rel: str) -> Path:
    if not isinstance(rel, str) or not rel or "\\" in rel or ":" in rel or "\x00" in rel:
        raise InvalidDistribution("invalid relative path")
    parts = rel.split("/")
    if any(p in {"", ".", ".."} for p in parts) or PurePosixPath(rel).is_absolute():
        raise InvalidDistribution("unsafe relative path")
    target = root.joinpath(*parts)
    current = root
    for p in parts:
        current = current / p
        if current.is_symlink():
            raise InvalidDistribution(f"symlink not allowed: {rel}")
    if not target.resolve().is_relative_to(root.resolve()):
        raise InvalidDistribution("path escapes package")
    return target

def read_file(root: Path, rel: str) -> bytes:
    p = safe_path(root, rel)
    if not p.is_file():
        raise InvalidDistribution(f"missing file: {rel}")
    if p.stat().st_size > MAX_FILE_BYTES:
        raise InvalidDistribution(f"file exceeds validator limit: {rel}")
    return p.read_bytes()

def read_json(root: Path, rel: str) -> Any:
    return load_json(read_file(root, rel))

def inventory(root: Path) -> set[str]:
    files: set[str] = set()
    for here, dirs, names in os.walk(root, followlinks=False):
        for name in dirs + names:
            p = Path(here) / name
            if p.is_symlink():
                raise InvalidDistribution("symlink found in distribution")
        for name in names:
            p = Path(here) / name
            rel = p.relative_to(root).as_posix()
            # Only local Python-generated bytecode is excluded; no arbitrary cache payloads.
            if p.suffix == ".pyc" and "__pycache__" in p.relative_to(root).parts:
                continue
            if not p.is_file():
                raise InvalidDistribution("non-regular path in distribution")
            if len(files) >= MAX_FILES:
                raise InvalidDistribution("too many files")
            files.add(rel)
    return files

def check_ref(root: Path, rel: str, *, origin: str | None = None) -> None:
    parts = urlsplit(rel)
    if parts.scheme or parts.netloc:
        if parts.scheme not in {"https", "http", "mailto"}:
            raise InvalidDistribution("unsupported reference scheme")
        return  # External links are not fetched or qualified.
    loc, frag = unquote(parts.path), unquote(parts.fragment)
    base = Path(origin).parent if origin else Path()
    # Markdown ../ links may resolve inside the root; manifest paths may not contain .. .
    target = (root / base / loc) if loc else (root / origin if origin else root)
    resolved = target.resolve()
    if not resolved.is_relative_to(root.resolve()):
        raise InvalidDistribution("link escapes distribution")
    canon = resolved.relative_to(root.resolve()).as_posix()
    p = safe_path(root, canon)
    # Check the unresolved path components too, to reject internal symlink aliases.
    probe = target
    while probe != root and probe != probe.parent:
        if probe.is_symlink():
            raise InvalidDistribution("symlink link target")
        probe = probe.parent
    if not p.is_file():
        raise InvalidDistribution(f"unresolved local reference: {rel}")
    if frag:
        if canon == "registry/RULES.json" and frag in EXPECTED_RULE_IDS:
            return  # Documented semantic record ID, not a browser anchor.
        text = read_file(root, canon).decode("utf-8")
        explicit = set(re.findall(r'<a\s+id=[\"\']([^\"\']+)[\"\']', text))
        if frag not in explicit:
            raise InvalidDistribution(f"unresolved explicit anchor: {rel}")

def verify(root: Path) -> dict[str, Any]:
    errors: list[str] = []
    checks: list[str] = []
    root = Path(root)
    if not root.is_dir() or root.is_symlink():
        return {"distribution": "AGHR Minimal", "version": VERSION,
                "verdict": "STRUCTURAL_FAIL", "errors": ["invalid distribution root"],
                "checks_passed": [], "qualification": QUALIFICATION.copy()}
    root = root.resolve()
    def run(label: str, fn: Any) -> None:
        try:
            fn()
        except (OSError, ValueError, TypeError, KeyError, AttributeError, UnicodeError) as exc:
            errors.append(f"{label}: {exc}")
        else:
            checks.append(label)
    def require(condition: bool, message: str) -> None:
        if not condition:
            raise InvalidDistribution(message)

    def manifest_check() -> None:
        m = read_json(root, "MANIFEST.json")
        require(m.get("distribution") == "AGHR Minimal" and m.get("version") == VERSION,
                "manifest identity mismatch")
        require(m.get("excluded") == ["MANIFEST.json", "generated __pycache__/*.pyc"], "unexpected exclusions")
        rows = m["files"]
        require(isinstance(rows, list) and 0 < len(rows) < MAX_FILES, "empty or invalid manifest")
        seen: set[str] = set()
        for row in rows:
            path = row["path"]
            require(path not in seen and path != "MANIFEST.json", "duplicate/self manifest entry")
            seen.add(path)
            data = read_file(root, path)
            require(type(row["bytes"]) is int and row["bytes"] >= 0, "invalid byte count")
            require(len(data) == row["bytes"] and digest(data) == row["sha256"], f"integrity mismatch: {path}")
        require(inventory(root) - {"MANIFEST.json"} == seen, "missing/unlisted distribution files")
    run("manifest_integrity_and_exact_inventory", manifest_check)

    def preserved_check() -> None:
        for path, expected in PRESERVED_HASHES.items():
            require(digest(read_file(root, path)) == expected, f"upstream-preserved file differs: {path}")
        require(read_file(root, "VERSION").decode().strip() == VERSION, "VERSION mismatch")
    run("seven_preserved_upstream_files_and_version", preserved_check)

    def rules_check() -> None:
        d = read_json(root, "registry/RULES.json")
        require(d.get("canonical") is True and d.get("version") == VERSION, "noncanonical rules")
        rows = d["rules"]
        ids = [x["id"] for x in rows]
        require(len(ids) == 47 and set(ids) == EXPECTED_RULE_IDS, "rule set mismatch")
        source_rows = read_json(root, "sources/REGISTER.json")["sources"]
        source_ids = [x["id"] for x in source_rows]
        require(len(source_ids) == 56 and len(set(source_ids)) == 56, "source set mismatch")
        for x in rows:
            for key in ("title", "text", "applies_when", "explanation_ref", "verification"):
                require(isinstance(x[key], str) and bool(x[key].strip()), f"empty {key}")
            require(x["force"] in {"MUST", "MUST_NOT", "SHOULD", "SHOULD_NOT", "MAY", "INFORMATIVE"}, "invalid force")
            require(type(x["waivable"]) is bool, "invalid waiver marker")
            require(all(b == "OWNER-FOUNDATION" or b in source_ids for b in x["basis"]), "unknown rule basis")
    run("canonical_rules_and_source_ids", rules_check)

    def routing_check() -> None:
        m = read_json(root, "REFERENCE_MAP.json")
        require(m.get("version") == VERSION and m.get("canonical_policy") == "registry/RULES.json", "routing identity")
        rows = m["rule_routes"]
        ids = [x["id"] for x in rows]
        require(len(ids) == 47 and set(ids) == EXPECTED_RULE_IDS, "routing rule coverage mismatch")
        canonical = {x["id"]: x for x in read_json(root, "registry/RULES.json")["rules"]}
        full_rows = m["full_only_references"]
        paths = [x["path"] for x in full_rows]
        require(len(paths) == len(set(paths)), "duplicate full-only reference")
        for row in full_rows:
            require(row["available_in_minimal"] is False, "full-only reference availability claim")
            require(not safe_path(root, row["path"]).exists(), "full-only implementation unexpectedly included")
        for row in rows:
            original = canonical[row["id"]]
            for key in ("force", "applies_when", "waivable"):
                require(row[key] == original[key], f"route changes rule semantics: {key}")
            exp = row["source_explanation_ref"]
            require(exp == original["explanation_ref"], "source explanation changed")
            exists = safe_path(root, exp).is_file()
            require(type(row["source_explanation_available_locally"]) is bool and row["source_explanation_available_locally"] == exists,
                    "incorrect explanation availability")
            require(exists or exp in paths, "source explanation neither local nor full-only")
            guides = row["minimal_guidance"]
            require(isinstance(guides, list) and len(guides) > 0, "missing minimal guidance")
            for ref in guides:
                check_ref(root, ref)
            check_ref(root, row["canonical_rule_ref"])
            require(row["canonical_rule_ref"] == "registry/RULES.json#"+row["id"], "wrong canonical pointer")
        policy = m["verification_reference_policy"]
        require(policy["behavioral_evaluation"] == "NOT_RUN" and policy["host_qualification"] == "NOT_RUN" and policy["independent_review"] == "NOT_PERFORMED", "unsupported qualification claim")
    run("all_rule_routes_and_explicit_full_only_references", routing_check)

    def json_check() -> None:
        for rel in inventory(root):
            if rel.endswith(".json"):
                read_json(root, rel)
    run("all_json_strict_parse", json_check)

    def links_check() -> None:
        for rel in inventory(root):
            if not rel.endswith(".md"):
                continue
            data = read_file(root, rel).decode("utf-8")
            data = re.sub(r"```[\s\S]*?```", "", data)
            for link in re.findall(r"(?<!!)\[[^\]\n]+\]\(([^)]+)\)", data):
                check_ref(root, link, origin=rel)
    run("markdown_local_links_and_explicit_anchors", links_check)

    def provenance_check() -> None:
        p = read_json(root, "PROVENANCE.json")
        require(p.get("version") == VERSION and p.get("derived_from_version") == VERSION, "provenance version")
        require(p.get("source_archive_sha256") == SOURCE_ARCHIVE_SHA256, "source archive baseline changed")
        require(p.get("canonical_rule_count") == 47 and p.get("normative_policy_change") is False, "normative scope claim")
        require(p.get("qualification") == QUALIFICATION, "unsupported adoption/qualification")
        rows = p["source_files_preserved_exact"]
        require(len(rows) == len(PRESERVED_HASHES), "preserved set count")
        require({x["path"]: x["sha256"] for x in rows} == PRESERVED_HASHES, "preserved baseline mismatch")
        for row in p["source_files_adapted_for_distribution"]:
            require(digest(read_file(root, row["path"])) == row["output_sha256"], "adapted file differs from declared derivative")
            require(bool(row.get("reason")), "missing adaptation rationale")
    run("provenance_and_no_inherited_qualification", provenance_check)

    return {"distribution": "AGHR Minimal", "version": VERSION,
            "verdict": "STRUCTURAL_FAIL" if errors else "STRUCTURAL_PASS",
            "checks_passed": checks, "errors": errors,
            "canonical_rule_count_expected": 47,
            "qualification": QUALIFICATION.copy(),
            "limits": ["No host/model behavior was tested by this verifier.",
                       "No source URLs were fetched; source records are inherited.",
                       "No approval or runtime permission is granted.",
                       "Checksums do not provide cryptographic authenticity."]}

def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parent)
    args = parser.parse_args()
    result = verify(args.root)
    print(json.dumps(result, ensure_ascii=False, indent=2))
    return 0 if result["verdict"] == "STRUCTURAL_PASS" else 1

if __name__ == "__main__":
    raise SystemExit(main())
